CREATE DATABASE BANKING ;
USE BANKING ;
-- 1. Create Customers Table
CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE
);

-- 2. Create Accounts Table
CREATE TABLE accounts (
    account_id INT PRIMARY KEY,
    customer_id INT FOREIGN KEY REFERENCES customers(customer_id),
    account_type VARCHAR(20) CHECK (account_type IN ('SAVINGS', 'CURRENT')),
    balance DECIMAL(12, 2) DEFAULT 0.00 CHECK (balance >= 0)
);

-- 3. Create Audit Trail Table for Transactions
CREATE TABLE transaction_log (
    log_id INT IDENTITY(1,1) PRIMARY KEY,
    account_id INT,
    transaction_type VARCHAR(20),
    amount DECIMAL(12, 2),
    transaction_date DATETIME DEFAULT GETDATE()
);
GO
--T-SQL Trigger (Automated Audit Logging)
CREATE OR ALTER TRIGGER trg_log_transaction
ON accounts
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    -- Handle Balance Deposit Log
    INSERT INTO transaction_log (account_id, transaction_type, amount)
    SELECT 
        i.account_id, 
        'DEPOSIT', 
        (i.balance - d.balance)
    FROM inserted i
    JOIN deleted d ON i.account_id = d.account_id
    WHERE i.balance > d.balance;

    -- Handle Balance Withdrawal Log
    INSERT INTO transaction_log (account_id, transaction_type, amount)
    SELECT 
        i.account_id, 
        'WITHDRAWAL', 
        (d.balance - i.balance)
    FROM inserted i
    JOIN deleted d ON i.account_id = d.account_id
    WHERE i.balance < d.balance;
END;
GO
--T-SQL Stored Procedure (Process Funds Transfer/Withdrawal)
CREATE OR ALTER PROCEDURE withdraw_funds
    @p_account_id INT,
    @p_amount DECIMAL(12, 2)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        -- Validate input amount
        IF @p_amount <= 0
        BEGIN
            RAISERROR('Withdrawal amount must be greater than zero.', 16, 1);
            RETURN;
        END

        -- Check if account exists
        IF NOT EXISTS (SELECT 1 FROM accounts WHERE account_id = @p_account_id)
        BEGIN
            RAISERROR('Account ID does not exist.', 16, 1);
            RETURN;
        END

        -- Begin Transaction for atomicity
        BEGIN TRANSACTION;

        DECLARE @v_current_balance DECIMAL(12, 2);

        -- Lock and fetch current balance
        SELECT @v_current_balance = balance 
        FROM accounts WITH (UPDLOCK)
        WHERE account_id = @p_account_id;

        -- Check sufficiency
        IF @v_current_balance < @p_amount
        BEGIN
            RAISERROR('Insufficient funds in account.', 16, 1);
        END

        -- Deduct amount
        UPDATE accounts
        SET balance = balance - @p_amount
        WHERE account_id = @p_account_id;

        COMMIT TRANSACTION;

        DECLARE @new_balance DECIMAL(12, 2) = @v_current_balance - @p_amount;
        PRINT 'Withdrawal successful! New balance: ' + CAST(@new_balance AS VARCHAR);

    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        PRINT 'Error: ' + ERROR_MESSAGE();
    END CATCH
END;
GO
--T-SQL User-Defined Function (Check Account Status)
CREATE OR ALTER FUNCTION get_account_status (
    @p_account_id INT
) 
RETURNS VARCHAR(20)
AS
BEGIN
    DECLARE @v_balance DECIMAL(12, 2);
    DECLARE @v_status VARCHAR(20);

    SELECT @v_balance = balance
    FROM accounts
    WHERE account_id = @p_account_id;

    IF @v_balance IS NULL
        SET @v_status = 'ACCOUNT_NOT_FOUND';
    ELSE IF @v_balance >= 50000
        SET @v_status = 'PLATINUM';
    ELSE IF @v_balance >= 10000
        SET @v_status = 'GOLD';
    ELSE
        SET @v_status = 'STANDARD';

    RETURN @v_status;
END;
GO
